import json

def generate_product_description(raw_data)->str:
    prompt = f"""
    Ты — эксперт в e-commerce и копирайтинге. 
    Твоя задача: на основе сырых данных от поставщика создать продающее название и описание товара.

    ДАННЫЕ ПОСТАВЩИКА:
    - "Вот данные товара в JSON: {json.dumps(raw_data, ensure_ascii=False)}. Сделай из этого описание.

    ТРЕБОВАНИЯ К ОТВЕТУ:
    1. Название: Привлекательное, включает ключевые слова, до 80 символов.
    2. Описание: Продающий текст на 3-4 абзаца. Используй метод (Pain-Agitation-Solution) или просто выдели выгоды.
    3. Список преимуществ: 3-5 буллитов (почему это стоит купить).

    Отвечай строго на русском языке.
    """
    return prompt


