import json

def prompt(raw_data: dict) -> str:
    full_json_context = json.dumps(raw_data, ensure_ascii=False, indent=2)
    return f"""
Ты — ассистент, возвращающий только один JSON-объект без каких-либо дополнительных пояснений, без дублирования запроса, без текста до или после.

Задача: на основе сырых данных товара создай продающее название и описание. Данные:
{full_json_context}

Требования к генерации:
- Название до 80 символов, включает бренд и назначение.
- Описание: продающий текст (3-4 абзаца) + в конце маркированный список из 4-6 ключевых характеристик.
- Язык: русский.

Ответ должен быть ровно одним JSON-объектом следующей структуры:
{{"name": "...", "description": "..."}}

Никаких других полей, никаких комментариев, никаких дублей. Начинай с {{ и заканчивай }}.
"""


